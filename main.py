def draw():
    c = Canvas(W, H, OCEAN)

    # Header band.
    c.fill_rect(0, 0, W, 152, HEADER)
    c.text_centered(0, W, 20, "THE WORLD", 7, WHITE)
    c.text_centered(0, W, 84, "22 NOVEMBER 2026", 6, GOLD)
    c.fill_rect(0, 152, W, 156, GOLD)

    # Faint graticule.
    for lon in range(-150, 181, 30):
        x, _ = project(lon, 0)
        c.vline(x, MAP_Y0, MAP_Y0 + MAP_H, GRID)
    for lat in (60, 30, 0, -30):
        _, y = project(0, lat)
        c.hline(MAP_X0, MAP_X0 + MAP_W, y, GRID)

    # Continents.
    for poly in CONTINENTS:
        pts = [project(lon, lat) for lon, lat in poly]
        c.fill_poly(pts, LAND)
        c.poly_outline(pts, LAND_EDGE)

    # Ocean labels, placed in clear water.
    lx, ly = project(-38, 15)
    c.text(lx - text_width("ATLANTIC", 2) // 2, ly, "ATLANTIC", 2, GRID)
    lx, ly = project(-140, -10)
    c.text(lx - text_width("PACIFIC OCEAN", 2) // 2, ly, "PACIFIC OCEAN", 2, GRID)

    # Numbered markers.
    for num, lon, lat, _text in STORIES:
        mx, my = project(lon, lat)
        c.fill_circle(mx, my, 15, RED_EDGE)
        c.fill_circle(mx, my, 13, RED)
        label = str(num)
        c.text(mx - text_width(label, 3) // 2, my - 10, label, 3, WHITE)

    # Legend panel.
    c.fill_rect(0, 715, W, H, PANEL)
    c.fill_rect(0, 715, W, 719, GOLD)
    y = 732
    for num, _lon, _lat, text in STORIES:
        c.fill_circle(46, y + 10, 15, RED_EDGE)
        c.fill_circle(46, y + 10, 13, RED)
        label = str(num)
        c.text(46 - text_width(label, 3) // 2, y, label, 3, WHITE)
        c.text(78, y, text, 3, INK)
        y += 34

    return c


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    canvas = draw()
    write_png(os.path.join(out_dir, "entry.png"), canvas)


